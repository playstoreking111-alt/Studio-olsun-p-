local urls = {}

-- linkleri çek
for url in source:gmatch('https://[%w%p]+') do
    if url:find("raw") then
        table.insert(urls, url)
    end
end

-- bildirim fonksiyonu
local function notify(text)
    pcall(function()
        StarterGui:SetCore("SendNotification", {
            Title = "Downloader",
            Text = text,
            Duration = 3
        })
    end)
end

-- indirme
for i, url in ipairs(urls) do
    local success, data = pcall(function()
        return game:HttpGet(url)
    end)

    if success and data then
        -- dosya ismini linkten çek
        local name = url:match("/([^/]+)$") or ("file_"..i)
        
        -- uzantı yoksa ekle
        if not name:find("%.lua") then
            name = name .. ".lua"
        end

        writefile(name, data)

        print("indirildi:", name)
        notify("indirildi: "..name)
    else
        warn("hata:", url)
        notify("hata: indirilemedi")
    end
end

